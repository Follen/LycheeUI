return function(library,check,near)
 local ctx=library:CreateContext({theme={fontSizeDelta=3,lineHeightDelta=4}})
 local plain=library:CreateContext();local C=ctx.C
 local parent=CreateFrame("Frame",nil,UIParent);parent:SetSize(800,600)
 local function size(region) return select(2,region:GetFont()) end
 local text=C.Text(parent,"Example",14,nil,nil,20)
 check(size(text)==17 and near(text:GetLineHeight(),24),"text applies context font and line deltas once")
 C.SetFont(text,14);C.SetLineHeight(text,20)
 check(size(text)==17 and near(text:GetLineHeight(),24),"explicit base font and line sizes remain idempotent")
 local button=C.Button(parent,"Action",120,nil,{fontSize=14,lineHeight=20})
 check(size(button.label)==17 and button.label:GetHeight()==24,"button label options use base sizes")
 button:SetStyle({fontSize=16});button:SetStyle({fontSize=16})
 check(size(button.label)==19 and button.label:GetHeight()==24,"partial font styling retains the base line height without accumulating delta")
 button:SetStyle({lineHeight=22});button:SetStyle({lineHeight=22})
 check(size(button.label)==19 and button.label:GetHeight()==26,"partial line styling retains the base font without accumulating delta")
 local edit=C.Edit(parent,240,44)
 check(size(edit.box)==17,"ordinary input uses its context font delta")
 ctx:OpenMenu(button,{{value=1,label="Menu item"}},function() end)
 local menu=ctx:GetMenu()
 check(size(menu.measure)==19 and size(menu.list.rows[1].title)==19 and menu.list.rows[1].title:GetHeight()==26,"menu measurement and visible labels share the adjusted font and line box")
 ctx:CloseMenu()
 local native=CreateFrame("EditBox",nil,parent);native:SetFont("native-font",12,"")
 native.Instructions=plain.C.Text(native,"Placeholder",12)
 local lease=C.NativeInput(edit,native)
 lease:RefreshStyle();lease:RefreshStyle()
 check(size(native)==17 and size(native.Instructions)==17,"native input and placeholder refresh from base font instead of accumulating delta")
 lease:Release()
 check(size(native)==12 and size(native.Instructions)==12,"native release restores the original input and placeholder fonts")
 ctx:SetFont("scaled-font",1.3)
 check(near(size(text),17*1.3) and near(text:GetLineHeight(),24*1.3),"context font scaling applies after base deltas")
 check(near(size(menu.measure),19*1.3) and near(size(menu.list.rows[1].title),19*1.3),"retained menu fonts update with their context")
 local later=C.Text(parent,"Later",14,nil,nil,20)
 check(near(size(later),17*1.3) and near(later:GetLineHeight(),24*1.3),"new controls inherit the current font scale")
 ctx:SetFont("scaled-font",.7);ctx:SetFont("scaled-font",1.3);ctx:SetFont("scaled-font",1)
 check(size(text)==17 and near(text:GetLineHeight(),24),"font scale round trips do not compound")
 ctx:SetFont("scaled-font",1.3)
 button:SetStyle({fontSize=16});button:SetStyle({lineHeight=22})
 check(near(size(button.label),19*1.3) and near(button.label:GetHeight(),26*1.3),"partial restyling retains unscaled font and line bases")
 lease=C.NativeInput(edit,native)
 ctx:SetFont("small-font",.7)
 check(near(size(native),17*.7) and near(size(native.Instructions),17*.7),"owned native leases immediately use the new font percentage")
 lease:Release()
 check(native:GetFont()=="native-font" and size(native)==12,"scaled native leases restore the original font")
 lease=C.NativeInput(edit,native)
 local foreign=CreateFrame("Frame",nil,UIParent);native:SetParent(foreign);native:SetFont("foreign-font",19,"")
 ctx:SetFont("another-font",1.3);lease:Release()
 check(native:GetFont()=="foreign-font" and size(native)==19,"restyling skips a native lease lost to another host")
 local normal=plain.C.Text(parent,"Unscaled",14,nil,nil,20)
 local normalButton=plain.C.Button(parent,"Normal",120)
 check(size(normal)==14 and near(normal:GetLineHeight(),20) and size(normalButton.label)==14 and normalButton.label:GetHeight()==20,"another default context retains its original text and button sizes")
 check(plain.Theme.fontSizeDelta==0 and plain.Theme.lineHeightDelta==0,"font policy does not leak between contexts")
 local menuFont=library:CreateContext({font="custom-menu-font"})
 local trigger=menuFont.C.Button(parent,"Menu",100);local entries={{value=1,label="A menu label with enough width"}}
 menuFont:OpenMenu(trigger,entries)
 local customMenu=menuFont:GetMenu()
 check(customMenu.measure:GetFont()=="custom-menu-font" and customMenu.list.rows[1].title:GetFont()=="custom-menu-font","menu measurement uses the initial context font path")
 local nativeWidth=customMenu.measure.GetStringWidth
 customMenu.measure.GetStringWidth=function(self) return nativeWidth(self)*(self:GetFont()=="custom-menu-font" and 2 or 1) end
 menuFont:CloseMenu();menuFont:OpenMenu(trigger,entries);local wide=customMenu:GetWidth()
 menuFont:SetFont("replacement-menu-font")
 check(customMenu.measure:GetFont()=="replacement-menu-font" and customMenu.list.rows[1].title:GetFont()=="replacement-menu-font" and customMenu:GetWidth()<wide,"open menu remeasurement and labels use the replacement context font")
 local replacedWidth=customMenu:GetWidth();menuFont:CloseMenu();menuFont:OpenMenu(trigger,entries)
 check(customMenu.measure:GetFont()=="replacement-menu-font" and customMenu:GetWidth()==replacedWidth,"reopened menus retain the current context font for measurement")
 menuFont:CloseMenu()
 local fixedMenuFont=library:CreateContext({font="context-menu-font",elements={["menu.row"]={base={label={font="fixed-menu-font"}}}}})
 local fixedTrigger=fixedMenuFont.C.Button(parent,"Menu",100);fixedMenuFont:OpenMenu(fixedTrigger,entries)
 local fixedMenu=fixedMenuFont:GetMenu();fixedMenuFont:SetFont("changed-context-font")
 check(fixedMenu.measure:GetFont()=="fixed-menu-font" and fixedMenu.list.rows[1].title:GetFont()=="fixed-menu-font","explicit menu element fonts override the context during measurement and refresh")
 fixedMenuFont:CloseMenu()
end
