return function(S,library,check,near)
 local original=library:CreateContext()
 local primary,high,low,secondary={.2,.3,.4,1},{.1,.2,.3,1},{.3,.2,.1,1},{.4,.3,.2,1}
 local hover,pressed={1,1,1,.1},{1,1,1,.2}
 local ctx=library:CreateContext({theme={primary=primary,surfaceHigh=high,surfaceLow=low,secondaryContainer=secondary,rowHover=hover,pressed=pressed}})
 local T=ctx.Theme
 check(T.accent==primary and T.field==high and T.fieldFocus==high and T.raised==high,"theme aliases resolve from context overrides")
 check(T.selected==secondary and T.surfaceHover==hover and T.hover==T.surfaceHighest,"secondary and hover aliases resolve together")
 check(near(T.surfaceHighest[1],.19) and near(T.surfaceLowHover[1],.37) and near(T.surfaceLowPressed[1],.44) and near(T.refreshHover[1],.46),"hover and pressed colors use overridden base colors and layers")
 check(original.Theme.accent==library.Theme.accent and original.Theme.surfaceHighest==library.Theme.surfaceHighest,"resolving another theme leaves existing contexts and defaults unchanged")
 local explicit={.8,.7,.6,1}
 local resolved=library.ResolveTheme({primary=primary,accent=explicit,surfaceHigh=high,field=explicit,surfaceHighest=explicit,hover=low})
 check(resolved.accent==explicit and resolved.field==explicit and resolved.surfaceHighest==explicit and resolved.hover==low,"explicit aliases and derived tokens take priority")
 local defaults=library.ResolveTheme()
 for key,value in pairs(library.Theme) do check(defaults[key]==value,"default theme preserves token "..key) end
 local frame=CreateFrame("Frame",nil,UIParent);frame:SetSize(240,160);frame:SetPoint("TOPLEFT",UIParent,"TOPLEFT",31,-47)
 ctx:SetWindow(frame)
 ctx.Motion:SetPresence(1)
 local point,parent,relative,x,y=frame:GetPoint()
 check(ctx.frame==frame,"SetWindow attaches the supplied window")
 check(point=="TOPLEFT" and parent==UIParent and relative=="TOPLEFT" and x==31 and y==-47,"Presence preserves the supplied window anchor")
 local replacement=CreateFrame("Frame",nil,UIParent);replacement:SetPoint("CENTER",UIParent,"CENTER",0,0);replacement:SetAlpha(.2)
 ctx:SetWindow(replacement);ctx.Motion:SetPresence(1)
 check(replacement:GetAlpha()==1,"SetWindow invalidates opacity writes belonging to the previous window")
 ctx:SetWindow(frame)
 local region=frame:CreateTexture(nil,"ARTWORK");region:SetSize(60,32);region:SetAlpha(.8);region:SetPoint("BOTTOMRIGHT",frame,"BOTTOMRIGHT",-9,13)
 local M=ctx.Motion
 M:Waiting(region,true);M:Tick(.6)
 local _,_,_,wx,wy=region:GetPoint()
 check(near(region:GetWidth(),62.1) and near(region:GetHeight(),31.2) and wx==-9 and near(wy,16),"waiting applies the original peak curve to the supplied geometry")
 M:Waiting(region,true);M:Tick(.6)
 check(near(region:GetWidth(),62.1) and near(select(5,region:GetPoint()),16),"restarting waiting does not capture an intermediate pose")
 M:Waiting(region,false)
 point,parent,relative,x,y=region:GetPoint()
 check(region:GetWidth()==60 and region:GetHeight()==32 and near(region:GetAlpha(),.8) and not region:IsShown(),"waiting cancellation restores original dimensions and opacity")
 check(point=="BOTTOMRIGHT" and parent==frame and relative=="BOTTOMRIGHT" and x==-9 and y==13,"waiting cancellation restores its original anchor")
 M:Waiting(region,true);M:Tick(.2);M:Stop(region)
 check(region:GetWidth()==60 and select(5,region:GetPoint())==13 and not next(M.waiting),"direct Stop releases waiting geometry ownership")
 M:Waiting(region,true);M:Tick(.2);M:StopAll()
 check(region:GetHeight()==32 and near(region:GetAlpha(),.8) and select(5,region:GetPoint())==13,"StopAll restores a waiting region")
 region:SetAlpha(.42)
 M:Busy(region,true);M:Tick(.2);check(not near(region:GetAlpha(),.42),"Busy retains its existing pulse")
 M:Busy(region,false);check(near(region:GetAlpha(),.42) and not region:IsShown(),"Busy cancellation restores initial alpha")
 M:Busy(region,true);M:Tick(.2);M:StopAll()
 check(near(region:GetAlpha(),.42) and not next(M.busy),"StopAll restores Busy alpha and releases its state")
 check(M:Count()==0 and not M.running and M.driver:GetScript("OnUpdate")==nil,"stopped context leaves no idle animation work")
end
