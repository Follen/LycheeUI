local S=dofile('tests/stubs.lua');S.Install()
local private={};local f=assert(io.open('embeds.xml'));local xml=f:read('*a');f:close()
for file in xml:gmatch('<Script file="([^"]+)"') do assert(loadfile(file))('NativeReacquire',private) end
local Library=private.LycheeUI;local count=0
local function check(value,message) count=count+1;assert(value,message) end
dofile('tests/native.lua')(Library,S,check)
local ctx=Library:CreateContext({reducedMotion=true});local C=ctx.C
local home=CreateFrame('Frame',nil,UIParent);local foreign=CreateFrame('Frame',nil,UIParent)
local input=CreateFrame('EditBox',nil,home);input:SetSize(180,24);input:SetFont('original',12,'')
local field=C.Field(UIParent,300,44);local stock,newCalls=0,0
input:SetScript('OnTextChanged',function() stock=stock+1 end)
local first=C.NativeInput(field,input,{scripts={OnTextChanged=function() error('released callback ran') end}})
local oldText=input:GetScript('OnTextChanged');local oldHide=input:GetScript('OnHide')
first:Release()
local second=C.NativeInput(field,input,{scripts={OnTextChanged=function() newCalls=newCalls+1 end}})
local currentText=input:GetScript('OnTextChanged')
check(first~=second and not first:IsOwned() and second:IsOwned(),'reacquisition creates a new public lease identity')
oldText(input,false)
check(stock==1 and newCalls==0 and input:GetScript('OnTextChanged')==currentText and second:IsOwned(),'stale wrappers forward only their captured stock handler and leave the new binding intact')
input:SetFocus();oldHide(input)
check(input:HasFocus() and field.focused and second:IsOwned(),'a stale hide callback cannot clear the current lease focus')
input:SetFont('later',19,'OUTLINE');first:RefreshStyle()
check(input:GetFont()=='later' and select(2,input:GetFont())==19,'a stale RefreshStyle cannot repaint the newly leased input')
second:RefreshStyle();input:SetParent(foreign);input:SetFont('foreign',21,'OUTLINE');input:Fire('OnTextChanged',false)
check(not second.active and newCalls==0 and input:GetParent()==foreign and input:GetFont()=='foreign','foreign handoff still releases bindings without overwriting the new host font')
local region=CreateFrame('Frame',nil,home);local lease=C.NativeFrame(region,field)
local hidden=region:CreateTexture(nil,'ARTWORK');hidden:SetAlpha(.42);hidden:Hide()
local changed=region:CreateTexture(nil,'ARTWORK');changed:SetAlpha(.7)
lease:Quiet(hidden);lease:Quiet(hidden);lease:Quiet(changed)
region:SetParent(foreign);changed:SetAlpha(.9);changed:Show();lease:Release()
check(hidden:GetAlpha()==.42 and not hidden:IsShown(),'repeated quiet calls retain the initial hidden flag and alpha')
check(changed:GetAlpha()==.9 and changed:IsShown(),'parallel quiet snapshots preserve decoration changed by a foreign host')
check(next(ctx.nativeControls)==nil and #ctx.inputs==0,'reacquisition and handoff leave no active registrations')
print('LycheeUI native lifecycle: '..count..' checks passed')
